const LABELS: ReadonlyMap<string, string> = new Map(
  Object.entries(FENCES_BY_LANGUAGE).flatMap(([name, fences]) => fences.map((fence) => [fence, name] as const)),
)

/**
 * The fences of the common languages, which the page loads in the background
 * once the first conversation has shown, so that such code shows in its
 * colors at once (`highlighter.ts`).
 */
export const COMMON_FENCES: readonly string[] = [
  'ts', 'typescript', 'tsx', 'js', 'javascript', 'jsx', 'json', 'md', 'markdown', 'html', 'css', 'vue',
  'bash', 'sh', 'shell', 'python', 'py', 'rust', 'rs', 'yaml', 'yml', 'go',
]

/** The label of a fence: its language's full name, else the fence as written. */
export function fenceLabel(fence: string): string {
  return LABELS.get(fence.toLowerCase()) ?? fence
}
