//go:build devrecord

package text_test

// Development-only recorder (not committed): runs GNU coreutils for the case
// files in $CASES, compares with the Go utility and writes <util>_cases_test.go.

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/wspl/demi/internal/toolctx/toolctxtest"
	"github.com/wspl/demi/internal/tools/text"
)

type devCase struct {
	Name   string            `json:"name"`
	Args   []string          `json:"args"`
	Stdin  string            `json:"stdin"`
	Files  map[string]string `json:"files"`
	Latin1 bool              `json:"latin1"`
}

func latin1(s string) string {
	b := make([]byte, 0, len(s))
	for _, r := range s {
		b = append(b, byte(r))
	}
	return string(b)
}

func TestDevRecord(t *testing.T) {
	dir := os.Getenv("CASES")
	only := os.Getenv("ONLY")
	paths, _ := filepath.Glob(filepath.Join(dir, "*.json"))
	for _, path := range paths {
		util := strings.TrimSuffix(filepath.Base(path), ".json")
		if only != "" && only != util {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		var cases []devCase
		if err := json.Unmarshal(data, &cases); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		var recorded []gnuCase
		for _, c := range cases {
			if c.Latin1 {
				c.Stdin = latin1(c.Stdin)
				for k, v := range c.Files {
					c.Files[k] = latin1(v)
				}
			}
			want := runGNU(t, c)
			got := runGo(t, c)
			if !sameCase(want, got) {
				t.Errorf("%s/%s %q:\n  gnu: code=%d out=%q err=%q after=%q\n  go:  code=%d out=%q err=%q after=%q",
					util, c.Name, c.Args, want.Code, want.Stdout, want.Stderr, want.After, got.Code, got.Stdout, got.Stderr, got.After)
			}
			recorded = append(recorded, want)
		}
		if os.Getenv("WRITE") != "" {
			writeCases(t, util, recorded)
		}
	}
}

func sameCase(a, b gnuCase) bool {
	return a.Code == b.Code && a.Stdout == b.Stdout && a.Stderr == b.Stderr && fmt.Sprint(a.After) == fmt.Sprint(b.After)
}

func runGNU(t *testing.T, c devCase) gnuCase {
	dir := t.TempDir()
	writeTree(t, dir, c.Files)
	cmd := exec.Command("/usr/bin/"+c.Args[0], c.Args[1:]...)
	cmd.Args[0] = c.Args[0]
	cmd.Dir = dir
	cmd.Env = []string{"LC_ALL=C", "TZ=UTC", "HOME=" + dir, "PATH=/usr/bin:/bin"}
	cmd.Stdin = strings.NewReader(c.Stdin)
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	code := 0
	if err := cmd.Run(); err != nil {
		code = cmd.ProcessState.ExitCode()
	}
	return result(t, c, dir, code, stdout.String(), stderr.String())
}

func runGo(t *testing.T, c devCase) gnuCase {
	dir := t.TempDir()
	writeTree(t, dir, c.Files)
	runner := &toolctxtest.Runner{Dir: dir, Env: toolctxtest.Env{"LC_ALL": "C", "TZ": "UTC", "HOME": dir}}
	utility := text.Utilities[c.Args[0]]
	if utility == nil {
		return gnuCase{Code: -1}
	}
	r := runner.Run(context.Background(), utility, c.Args, c.Stdin)
	return result(t, c, dir, r.Code, r.Stdout, r.Stderr)
}

func result(t *testing.T, c devCase, dir string, code int, stdout, stderr string) gnuCase {
	files := c.Files
	after := readTree(t, dir)
	out := gnuCase{Name: c.Name, Args: c.Args, Stdin: c.Stdin, Files: files, Stdout: stdout, Code: code, Stderr: stderr}
	if !sameTree(after, files) {
		out.After = after
	}
	return out
}

func writeCases(t *testing.T, util string, cases []gnuCase) {
	var b strings.Builder
	b.WriteString("// Code generated by recording GNU coreutils 9.4 with LC_ALL=C. DO NOT EDIT.\n\npackage text_test\n\n")
	fmt.Fprintf(&b, "var %sCases = []gnuCase{\n", util)
	for _, c := range cases {
		fmt.Fprintf(&b, "\t{\n\t\tName: %q,\n\t\tArgs: %#v,\n", c.Name, c.Args)
		if c.Stdin != "" {
			fmt.Fprintf(&b, "\t\tStdin: %q,\n", c.Stdin)
		}
		if len(c.Files) > 0 {
			fmt.Fprintf(&b, "\t\tFiles: %s,\n", mapLit(c.Files))
		}
		if c.Stdout != "" {
			fmt.Fprintf(&b, "\t\tStdout: %q,\n", c.Stdout)
		}
		if c.Code != 0 {
			fmt.Fprintf(&b, "\t\tCode: %d,\n", c.Code)
		}
		if c.Stderr != "" {
			fmt.Fprintf(&b, "\t\tStderr: %q,\n", c.Stderr)
		}
		if c.After != nil {
			fmt.Fprintf(&b, "\t\tAfter: %s,\n", mapLit(c.After))
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	if err := os.WriteFile(util+"_cases_test.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

func mapLit(m map[string]string) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("map[string]string{")
	for i, k := range keys {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q: %q", k, m[k])
	}
	b.WriteString("}")
	return b.String()
}
