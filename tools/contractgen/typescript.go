const tsHeader = "// Code generated by contractgen; DO NOT EDIT.\n"

// isTSExport keeps factored values private unless rooted. A schema-primitive
// root only exports a name when explicitly selected for TypeScript.
func isTSExport(d *definition) bool {
	if has(d.marks, "schema-primitive") {
		return bounds(d.marks["root"])["output"] != ""
	}
	return has(d.marks, "root") || !has(d.marks, "variant") && !isPrivateValue(d)
}

// exportsTS gives pages their manifest's named definitions. Explicit page roots
// remain visible to the consistency check even when absent from the manifest.
func (g *generator) exportsTS(d *definition) bool {
	if g.pageNames != nil {
		_, declared := g.pageNames[tsName(d.name)]
		return declared || bounds(d.marks["root"])["output"] == g.tsOutput
	}
	return isTSExport(d)
}

// markReceived follows reachable contracts. MessagePack excludes keys because
// map keys use string encoding rather than the named type's value codec.
func (g *generator) markReceived(name string, includeKeys bool) {
	if g.received[name] {
		return
	}
	g.received[name] = true
	d := g.defs[name]
	if d == nil {
		g.err = fmt.Errorf("external contract %s is not loaded", name)
		return
	}
	if has(d.marks, "codec") {
		return
	}
	if has(d.marks, "union") {
		for _, v := range g.variants(name) {
			g.markReceived(v.key, includeKeys)
		}
	}
	var visit func(types.Type)
	visit = func(t types.Type) {
		if isJSON(t) {
			return
		}
		switch t := t.(type) {
		case *types.Named:
			g.markReceived(typeKey(t), includeKeys)
		case *types.Pointer:
			visit(t.Elem())
		case *types.Slice:
			visit(t.Elem())
		case *types.Map:
			if includeKeys {
				visit(t.Key())
			}
			visit(t.Elem())
		case *types.Struct:
			for i := 0; i < t.NumFields(); i++ {
				visit(t.Field(i).Type())
			}
		}
	}
	visit(d.typ.Underlying())
}

func (g *generator) emitTS(name string) {
	d := g.defs[name]
	if old, ok := g.tsNames[tsName(d.name)]; ok && old != name {
		g.err = fmt.Errorf("%s: %s: duplicate TypeScript name also from %s", d.position, d.name, old)
		return
	}
	g.tsNames[tsName(d.name)] = name
	if g.shared[name] && isTSExport(d) {
		g.tsImports[schema(d.name)] = true
		return
	}
	diagnosticName := d.name
	defer func() {
		if g.err != nil {
			g.err = fmt.Errorf("%s: %s: %w", d.position, diagnosticName, g.err)
		}
	}()
	if g.emitted[name] || g.active[name] {
		return
	}
	g.active[name] = true
	if g.adjacentUnion(d) != nil {
		g.err = fmt.Errorf("adjacent union variant is not supported in TypeScript")
		return
	}
	if has(d.marks, "codec") && d.marks["codec"] != "string" {
		g.err = fmt.Errorf("codec has no explicit TypeScript mapping")
		return
	}
	code, ok := g.tsDefinition(d, name, &diagnosticName)
	if !ok {
		return
	}
	g.writeTSDeclaration(d, code)
	g.active[name] = false
	g.emitted[name] = true
}

func (g *generator) tsType(t types.Type, m map[string]string) (string, bool) {
	if isJSON(t) {
		if has(m, "object") {
			return "z.record(z.string(), z.json())", false
		}
		return "z.json()", false
	}
	code := ""
	forward := false
	switch t := t.(type) {
	case *types.Pointer:
		return g.tsType(t.Elem(), m)
	case *types.Named:
		key := typeKey(t)
		forward = g.active[key]
		g.emitTS(key)
		code = schema(t.Obj().Name())
	case *types.Slice:
		if types.Identical(t.Elem(), types.Typ[types.Uint8]) {
			if has(m, "length") {
				g.err = fmt.Errorf("binary length rules are outside the supported Zod subset")
			}
			return base64Schema, false
		}
		item, f := g.tsType(t.Elem(), map[string]string{})
		code = "z.array(" + item + ")"
		forward = f
	case *types.Map:
		item, f := g.tsType(t.Elem(), map[string]string{})
		if isPointer(t.Elem()) {
			item += ".nullable()"
		}
		code = "z.record(z.string(), " + item + ")"
		forward = f
	case *types.Basic:
		code = g.tsScalar(t, m)
	default:
		g.err = fmt.Errorf("unsupported TypeScript shape %s", t)
	}
	code = tsRules(t, m, code)
	return code, forward
}

// Zod checks alphabet and padding length, but not unused padding bits. The
// additional pattern matches the canonical bytes accepted by Go's Strict codec.
const base64Schema = `z.base64().regex(/^(?:[A-Za-z0-9+/]{4}` +
	`)*(?:[A-Za-z0-9+/][AQgw]==|[A-Za-z0-9+/]{2}[AEIMQUYcgkosw048]=)?$/)`

func (g *generator) tsUnion(d *definition, name string) string {
	var code string
	if bounds(d.marks["union"])["content"] != "" {
		g.err = fmt.Errorf("adjacent union is not supported in TypeScript")
		return ""
	}
	tag := bounds(d.marks["union"])["tag"]
	var variants []string
	declarations := g.variants(name)
	// Zod numbers recursive JSON definitions in traversal order. Variants
	// follow declaration order, including discriminated unions.
	sort.SliceStable(declarations, func(i, j int) bool {
		return declarations[i].typ.Obj().Pos() < declarations[j].typ.Obj().Pos()
	})
	for _, v := range declarations {
		g.emitTS(v.key)
		_, value, _ := strings.Cut(v.marks["variant"], " ")
		if d.marks["union"] == "untagged" {
			variants = append(variants, schema(v.name))
		} else {
			variants = append(variants, schema(v.name)+".extend({"+quote(tag)+": z.literal("+tagLiteral(value)+")})")
		}
	}
	if d.marks["union"] == "untagged" {
		code = "z.union([" + strings.Join(variants, ", ") + "])"
	} else {
		code = "z.discriminatedUnion(" + quote(tag) + ", [" + strings.Join(variants, ", ") + "])"
	}
	return code
}

func (g *generator) tsObject(d *definition, st *types.Struct, name string, diagnosticName *string) string {
	var code string
	var fields []string
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if child := g.optionalObject(f); child != nil {
			g.emitTS(child.key)
			fields = append(fields, "..."+schema(child.name)+".partial().shape")
			continue
		}
		opts := strings.Split(reflect.StructTag(st.Tag(i)).Get("json"), ",")
		value, forward := g.tsType(f.Type(), d.fields[f.Name()])
		if g.err != nil {
			*diagnosticName += "." + f.Name()
			return ""
		}
		if has(d.fields[f.Name()], "nullable") {
			value += ".nullable()"
		}
		if len(opts) > 1 || has(d.fields[f.Name()], "default") {
			value += ".optional()"
		}
		if forward {
			fields = append(fields, "get "+quote(opts[0])+"() { return "+value+" }")
		} else {
			fields = append(fields, quote(opts[0])+": "+value)
		}
	}
	constructor := "z.object"
	if !g.received[name] {
		constructor = "z.strictObject"
		if has(d.marks, "tolerant") {
			g.err = fmt.Errorf("%s: send-only object must refuse unknown fields", name)
		}
	}
	code = constructor + "({" + strings.Join(fields, ", ") + "})"
	return code
}

func (g *generator) tsScalar(t *types.Basic, m map[string]string) string {
	var code string
	switch t.Kind() {
	case types.String:
		code = "z.string()"
	case types.Bool:
		code = "z.boolean()"
	case types.Float32, types.Float64:
		code = "z.number()"
	case types.Int8:
		code = "z.int().min(-128).max(127)"
	case types.Uint8:
		code = "z.int().min(0).max(255)"
	case types.Int16:
		code = "z.int().min(-32768).max(32767)"
	case types.Uint16:
		code = "z.int().min(0).max(65535)"
	case types.Int32:
		code = "z.int().min(-2147483648).max(2147483647)"
	case types.Uint32:
		code = "z.int().min(0).max(4294967295)"
	case types.Int, types.Int64, types.Uint, types.Uint64:
		b := bounds(m["range"])
		maximum, err := strconv.ParseFloat(b["max"], 64)
		if err != nil || maximum > 9007199254740991 {
			g.err = fmt.Errorf("%s: integer read by JavaScript requires a safe maximum", t)
		}
		code = "z.int()"
		if t.Info()&types.IsUnsigned != 0 {
			code += ".min(0)"
		} else {
			minimum, err := strconv.ParseFloat(b["min"], 64)
			if err != nil || minimum < -9007199254740991 {
				g.err = fmt.Errorf("%s: integer read by JavaScript requires a safe minimum", t)
			}
		}
	default:
		g.err = fmt.Errorf("unsupported TypeScript scalar %s", t)
	}
	return code
}

func (g *generator) writeTSDeclaration(d *definition, code string) {
	export := "export "
	if !g.exportsTS(d) {
		export = ""
	}
	fmt.Fprintf(
		&g.ts,
		"%sconst %s = %s\n%stype %s = z.infer<typeof %s>\n",
		export,
		schema(d.name),
		code,
		export,
		tsName(d.name),
		schema(d.name),
	)
}

func tsRules(t types.Type, m map[string]string, code string) string {
	switch m["format"] {
	case "trimmed":
		code += ".trim()"
	case "email":
		code = "z.email().max(254)"
	case "http-url":
		code = "z.url({ protocol: z.regexes.httpProtocol })"
	}
	if has(m, "timestamp") && !integerTimestamp(t) {
		code = "z.iso.datetime({ precision: 3 })"
	}
	if has(m, "base64") {
		code = base64Schema
	}
	if values := m["enum"]; values != "" {
		var vals []string
		for _, v := range strings.Fields(values) {
			vals = append(vals, quote(v))
		}
		code = "z.enum([" + strings.Join(vals, ", ") + "])"
	}
	for _, rule := range []string{"length", "range"} {
		b := bounds(m[rule])
		for _, key := range []string{"min", "max"} {
			if value := b[key]; value != "" && value != "9007199254740991" && value != "-9007199254740991" {
				code += "." + key + "(" + value + ")"
			}
		}
	}
	if pattern := m["pattern"]; pattern != "" {
		code += ".regex(new RegExp(" + quote(pattern) + ", \"u\"))"
	}

	return code
}

// tsDefinition reports whether emission should continue; diagnostics retain the failing field name.
func (g *generator) tsDefinition(d *definition, name string, diagnosticName *string) (string, bool) {
	var code string
	if has(d.marks, "union") {
		code = g.tsUnion(d, name)
		if code == "" {
			return "", false
		}
		return code, true
	}
	if st, ok := g.object(d); ok {
		code = g.tsObject(d, st, name, diagnosticName)
		if code == "" {
			return "", false
		}
		return code, true
	}
	var forward bool
	code, forward = g.tsType(d.typ.Underlying(), d.marks)
	if forward {
		g.err = fmt.Errorf("%s: recursion outside an object property", name)
	}
	return code, true
}
