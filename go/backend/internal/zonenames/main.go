// Command zonenames writes settings_zones_gen.go: the IANA time zone names of
// the Go toolchain's time zone database ($GOROOT/lib/time/zoneinfo.zip), which
// a reported locale's time zone is checked against. It runs under go generate
// in package backend.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
)

func main() {
	if err := write(); err != nil {
		fmt.Fprintf(os.Stderr, "zonenames: %v\n", err)
		os.Exit(1)
	}
}

func write() error {
	root := os.Getenv("GOROOT")
	if root == "" {
		return fmt.Errorf("GOROOT is not set: run this under go generate")
	}
	archive, err := zip.OpenReader(filepath.Join(root, "lib", "time", "zoneinfo.zip"))
	if err != nil {
		return err
	}
	defer archive.Close()
	var names []string
	for _, file := range archive.File {
		if !file.FileInfo().IsDir() {
			names = append(names, file.Name)
		}
	}
	slices.Sort(names)
	var source bytes.Buffer
	source.WriteString("// Code generated by internal/zonenames; DO NOT EDIT.\n\npackage backend\n\n")
	source.WriteString("// zoneNames are the IANA time zone names, sorted.\nvar zoneNames = []string{\n")
	for _, name := range names {
		fmt.Fprintf(&source, "\t%q,\n", name)
	}
	source.WriteString("}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("settings_zones_gen.go", formatted, 0o644)
}
