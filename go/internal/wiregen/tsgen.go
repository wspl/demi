package wiregen

import (
	"encoding/json/v2"
	"fmt"
	"go/constant"
	"strconv"
	"strings"
)

// tsHeader is the first lines of a generated TypeScript file.
const tsHeader = "// Generated by `go generate` (cmd/wiregen) from the Go wire types. Do not edit.\nimport { z } from \"zod\"\n"

// maxSafeInteger is the largest integer that JavaScript holds exactly.
const maxSafeInteger = 1<<53 - 1

// GenerateTypeScript returns the Zod v4 source of the package's wire types,
// with the `z.infer` type of each, in the format of the Rust contract emitter
// (crates/xtask/src/contracts/zod.rs): strict objects, optional members as
// `.optional()`, lengths in code points, closed sets of strings as `z.enum`,
// tagged unions as `z.discriminatedUnion`. A rule that only Go can check (a
// `func` rule, or a rule across fields) has no schema.
func (p *Package) GenerateTypeScript() ([]byte, error) {
	var names []string
	for _, file := range p.Files {
		names = append(names, file.Types...)
	}
	done := map[string]bool{}
	visiting := map[string]bool{}
	var out strings.Builder
	out.WriteString(tsHeader)
	var emit func(name string) error
	emit = func(name string) error {
		if done[name] {
			return nil
		}
		if visiting[name] {
			return fmt.Errorf("%s: a recursive wire type", name)
		}
		visiting[name] = true
		defer delete(visiting, name)
		for _, dependency := range p.dependencies(name) {
			if err := emit(dependency); err != nil {
				return err
			}
		}
		done[name] = true
		source, err := p.definition(name)
		if err != nil {
			return err
		}
		out.WriteString(source)
		return nil
	}
	for _, name := range names {
		if err := emit(name); err != nil {
			return nil, err
		}
	}
	return []byte(out.String()), nil
}

// dependencies returns the wire types that a type's schema refers to.
func (p *Package) dependencies(name string) []string {
	var found []string
	var walk func(t *Type)
	walk = func(t *Type) {
		switch t.Kind {
		case KindStruct, KindUnion:
			if !t.Opaque {
				found = append(found, t.Name)
			}
		case KindSlice, KindPointer:
			walk(t.Elem)
		case KindMap:
			walk(t.Elem)
		}
	}
	if u, ok := p.Unions[name]; ok {
		for _, v := range u.Variants {
			found = append(found, v.Name)
		}
		return found
	}
	for _, f := range p.Structs[name].Fields {
		walk(f.Type)
	}
	return found
}

// schemaName is the name a definition's schema is exported under: Block is
// blockSchema.
func schemaName(definition string) string {
	return strings.ToLower(definition[:1]) + definition[1:] + "Schema"
}

func (p *Package) definition(name string) (string, error) {
	var out strings.Builder
	out.WriteByte('\n')
	var code, doc string
	if u, ok := p.Unions[name]; ok {
		doc = u.Doc
		var refs []string
		for _, v := range u.Variants {
			refs = append(refs, schemaName(v.Name))
		}
		if u.TagName != "" {
			code = fmt.Sprintf("z.discriminatedUnion(%s, [%s])", quote(u.TagName), strings.Join(refs, ", "))
		} else {
			code = fmt.Sprintf("z.union([%s])", strings.Join(refs, ", "))
		}
	} else if s := p.Structs[name]; s.Scalar != nil {
		doc = s.Doc
		scalar, err := p.schema(s.Scalar, nil)
		if err != nil {
			return "", err
		}
		code = scalar
	} else {
		doc = s.Doc
		object, err := p.object(s)
		if err != nil {
			return "", err
		}
		code = object
	}
	pushDoc(&out, doc, 0)
	fmt.Fprintf(&out, "export const %s = %s\n", schemaName(name), code)
	fmt.Fprintf(&out, "export type %s = z.infer<typeof %s>\n", name, schemaName(name))
	return out.String(), nil
}

// object returns the strict object of a struct, whose members are written on
// lines of their own.
func (p *Package) object(s *Struct) (string, error) {
	var lines []string
	if s.Union != nil && s.Union.TagName != "" {
		lines = append(lines, fmt.Sprintf("  %s: z.literal(%s),\n", key(s.Union.TagName), quote(s.Tag)))
	}
	for _, f := range s.Fields {
		schema, err := p.schema(f.Type, f.Rules)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", s.Name, f.Name, err)
		}
		if f.Nullable {
			schema += ".nullable()"
		}
		if !f.Required {
			schema += ".optional()"
		}
		var line strings.Builder
		pushDoc(&line, f.Doc, 1)
		fmt.Fprintf(&line, "  %s: %s,\n", key(f.JSON), schema)
		lines = append(lines, line.String())
	}
	function := "z.strictObject"
	if s.Open {
		// Zod's object ignores the members it does not have.
		function = "z.object"
	}
	if len(lines) == 0 {
		return function + "({})", nil
	}
	return function + "({\n" + strings.Join(lines, "") + "})", nil
}

// schema returns the Zod schema of a value of type t under rules.
func (p *Package) schema(t *Type, rules []Rule) (string, error) {
	switch t.Kind {
	case KindPointer:
		return p.schema(t.Elem, rules)
	case KindStruct, KindUnion:
		if t.Opaque {
			return "", fmt.Errorf("%s is decoded by its package and has no TypeScript schema", t.Name)
		}
		return schemaName(t.Name), nil
	case KindBool:
		return "z.boolean()", nil
	case KindRaw:
		return "z.json()", nil
	case KindString:
		return p.stringSchema(rules)
	case KindInt, KindUint:
		return p.integerSchema(t, rules)
	case KindFloat:
		code := "z.number()"
		for _, rule := range rules {
			if rule.Kind != RuleRange {
				continue
			}
			if rule.Min != nil {
				code += fmt.Sprintf(".min(%s)", strconv.FormatFloat(rule.Min.Float, 'g', -1, 64))
			}
			if rule.Max != nil {
				code += fmt.Sprintf(".max(%s)", strconv.FormatFloat(rule.Max.Float, 'g', -1, 64))
			}
		}
		return code, nil
	case KindSlice:
		element, err := p.schema(t.Elem, eachRules(rules))
		if err != nil {
			return "", err
		}
		code := "z.array(" + element + ")"
		for _, rule := range rules {
			switch rule.Kind {
			case RuleItems:
				code += lengthBounds(rule)
			case RuleUnique:
				code += ".refine((items) => new Set(items).size === items.length, { message: \"has a duplicate element\" })"
			}
		}
		return code, nil
	case KindMap:
		element, err := p.schema(t.Elem, eachRules(rules))
		if err != nil {
			return "", err
		}
		keys := keyRules(rules)
		code := "z.record(z.string(), " + element + ")"
		if len(keys) > 0 {
			key, err := p.stringSchema(keys)
			if err != nil {
				return "", err
			}
			function := "z.record"
			if strings.HasPrefix(key, "z.enum(") {
				// A closed set of keys is a partial record: no key is required.
				function = "z.partialRecord"
			}
			code = function + "(" + key + ", " + element + ")"
		}
		for _, rule := range rules {
			if rule.Kind == RuleItems {
				code += lengthBounds(rule)
			}
		}
		return code, nil
	}
	return "", fmt.Errorf("no schema for %s", t.Src)
}

// eachRules returns the rules that apply to every element of a slice or every
// value of a map.
func eachRules(rules []Rule) []Rule {
	var inner []Rule
	for _, rule := range rules {
		if rule.Kind == RuleEach {
			inner = append(inner, rule.Inner...)
		}
	}
	return inner
}

func keyRules(rules []Rule) []Rule {
	var inner []Rule
	for _, rule := range rules {
		if rule.Kind == RuleKeys {
			inner = append(inner, rule.Inner...)
		}
	}
	return inner
}

// lengthBounds writes .min and .max of a rule's bounds.
func lengthBounds(rule Rule) string {
	var code string
	if rule.Min != nil {
		code += fmt.Sprintf(".min(%d)", rule.Min.Value)
	}
	if rule.Max != nil {
		code += fmt.Sprintf(".max(%d)", rule.Max.Value)
	}
	return code
}

func (p *Package) stringSchema(rules []Rule) (string, error) {
	code := "z.string()"
	for _, rule := range rules {
		switch rule.Kind {
		case RuleOneOf:
			values := make([]string, len(rule.Values))
			for i, value := range rule.Values {
				values[i] = quote(value)
			}
			return "z.enum([" + strings.Join(values, ", ") + "])", nil
		case RuleEq:
			return "z.literal(" + quote(rule.Value) + ")", nil
		}
	}
	for _, rule := range rules {
		switch rule.Kind {
		case RuleChars:
			code += lengthBounds(rule)
		case RuleBytes:
			if rule.Min != nil {
				code += fmt.Sprintf(".refine((value) => new TextEncoder().encode(value).length >= %d, { message: \"is too short\" })", rule.Min.Value)
			}
			if rule.Max != nil {
				code += fmt.Sprintf(".refine((value) => new TextEncoder().encode(value).length <= %d, { message: \"is too long\" })", rule.Max.Value)
			}
		case RulePattern:
			// `u`: the browser matches code points, as Go's regexp does.
			code += fmt.Sprintf(".regex(new RegExp(%s, \"u\"))", quote(p.patterns[rule.Value]))
		case RuleNoNUL:
			code += ".regex(new RegExp(" + quote(`^[^\u0000]*$`) + ", \"u\"))"
		}
	}
	return code, nil
}

// integerSchema writes z.int() with the bounds that are tighter than the safe
// integers: the type's own and the range rule's.
func (p *Package) integerSchema(t *Type, rules []Rule) (string, error) {
	for _, rule := range rules {
		if rule.Kind == RuleEq {
			value, err := p.evaluate(rule.Value)
			if err != nil {
				return "", err
			}
			return "z.literal(" + strconv.FormatInt(value, 10) + ")", nil
		}
	}
	bits := t.Bits
	if bits == 0 {
		bits = 64
	}
	lo, hi := int64(-maxSafeInteger), int64(maxSafeInteger)
	if t.Kind == KindUint {
		lo = 0
		if bits < 53 {
			hi = int64(1)<<bits - 1
		}
	} else if bits < 53 {
		lo, hi = -(int64(1) << (bits - 1)), int64(1)<<(bits-1)-1
	}
	for _, rule := range rules {
		if rule.Kind != RuleRange {
			continue
		}
		if rule.Min != nil {
			lo = max(lo, rule.Min.Value)
		}
		if rule.Max != nil {
			hi = min(hi, rule.Max.Value)
		}
	}
	code := "z.int()"
	if lo > -maxSafeInteger {
		code += fmt.Sprintf(".min(%d)", lo)
	}
	if hi < maxSafeInteger {
		code += fmt.Sprintf(".max(%d)", hi)
	}
	return code, nil
}

// evaluate returns the number that a literal or a constant's name stands for.
func (p *Package) evaluate(text string) (int64, error) {
	if n, err := strconv.ParseInt(text, 10, 64); err == nil {
		return n, nil
	}
	value, ok := p.consts[text]
	if !ok {
		return 0, fmt.Errorf("%s is neither a number nor a constant of the package", text)
	}
	n, exact := constant.Int64Val(constant.ToInt(value))
	if !exact {
		return 0, fmt.Errorf("%s is not an integer", text)
	}
	return n, nil
}

// quote returns text as a JavaScript string literal: JSON's quoting is
// JavaScript's.
func quote(text string) string {
	quoted, err := json.Marshal(text)
	if err != nil {
		panic(err)
	}
	return string(quoted)
}

// key returns a property name as an object literal's key.
func key(name string) string {
	identifier := name != ""
	for i, c := range name {
		letter := c == '_' || c == '$' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
		if !letter && (i == 0 || c < '0' || c > '9') {
			identifier = false
		}
	}
	if identifier {
		return name
	}
	return quote(name)
}

// pushDoc writes a description as a JSDoc comment at indent.
func pushDoc(out *strings.Builder, description string, indent int) {
	if description == "" {
		return
	}
	pad := strings.Repeat("  ", indent)
	text := strings.ReplaceAll(description, "*/", "*\\/")
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(out, "%s/** %s */\n", pad, lines[0])
		return
	}
	fmt.Fprintf(out, "%s/**\n", pad)
	for _, line := range lines {
		if line == "" {
			fmt.Fprintf(out, "%s *\n", pad)
		} else {
			fmt.Fprintf(out, "%s * %s\n", pad, line)
		}
	}
	fmt.Fprintf(out, "%s */\n", pad)
}
