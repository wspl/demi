// The import path of the runtime the generated code shares.
const wireImport = "github.com/wspl/demi/go/internal/wire"

// generatedHeader is the first line of every generated Go file, which the
// tools that skip generated code know.
const generatedHeader = "// Code generated by wiregen; DO NOT EDIT."

// optionsFile is the file that holds the package's json.Options.
const optionsFile = "options" + generatedSuffix

// GenerateGo returns the Go files of the package's decoders, rule checks and
// encoders, by name: one for each source file that declares wire types, and the
// package's options.
func (p *Package) GenerateGo() (map[string][]byte, error) {
	files := map[string][]byte{}
	for _, file := range p.Files {
		g := &goGen{imports: map[string]bool{wireImport: true}, unions: p.Unions}
		for alias, path := range file.Imports {
			g.imports[path] = true
			if alias != pathpkg.Base(path) {
				if g.aliases == nil {
					g.aliases = map[string]string{}
				}
				g.aliases[path] = alias
			}
		}
		for _, name := range file.Types {
			if s, ok := p.Structs[name]; ok && s.Scalar == nil && !s.Opaque {
				if err := g.structure(s); err != nil {
					return nil, err
				}
			}
			if u, ok := p.Unions[name]; ok {
				g.union(u)
			}
		}
		if g.buf.Len() == 0 {
			continue
		}
		out, err := g.finish(p.Name)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file.Name, err)
		}
		files[strings.TrimSuffix(file.Name, ".go")+generatedSuffix] = out
	}
	if len(p.Files) > 0 {
		options, err := p.options()
		if err != nil {
			return nil, err
		}
		files[optionsFile] = options
	}
	schemas, err := p.schemas()
	if err != nil {
		return nil, err
	}
	if schemas != nil {
		files[schemasFile] = schemas
	}
	packed, err := p.messagePack()
	if err != nil {
		return nil, err
	}
	if packed != nil {
		files["msgpack_wire.go"] = packed
	}
	exported, err := p.exports()
	if err != nil {
		return nil, err
	}
	if exported != nil {
		files["exports_wire.go"] = exported
	}
	return files, nil
}

// options writes the package's one json.Options value, which its decode and
// encode functions pass: maps come out in sorted key order, and each union is
// decoded by its own function. A variant encodes itself.
func (p *Package) options() ([]byte, error) {
	g := &goGen{imports: map[string]bool{"encoding/json/v2": true}}
	var unions []*Union
	for _, file := range p.Files {
		for _, name := range file.Types {
			if u, ok := p.Unions[name]; ok {
				unions = append(unions, u)
			}
		}
	}
	g.p("// wireOptions are the options of every decode and encode of the package's wire")
	g.p("// types: maps are encoded in sorted key order, and each union has its own")
	g.p("// decoder, which json needs to decode into an interface.")
	g.p("var wireOptions = json.JoinOptions(")
	g.p("\tjson.Deterministic(true),")
	if len(unions) > 0 {
		g.imports["encoding/json/jsontext"] = true
		g.p("\tjson.WithUnmarshalers(json.JoinUnmarshalers(")
		for _, u := range unions {
			g.p("\t\tjson.UnmarshalFromFunc(func(dec *jsontext.Decoder, v *%s) error {", u.Name)
			g.p("\t\t\tvalue, err := decode%s(dec)", u.Name)
			g.p("\t\t\tif err != nil {")
			g.p("\t\t\t\treturn err")
			g.p("\t\t\t}")
			g.p("\t\t\t*v = value")
			g.p("\t\t\treturn nil")
			g.p("\t\t}),")
		}
		g.p("\t)),")
	}
	g.p(")")
	g.p("")
	g.helpers(p.Name)
	return g.finish(p.Name)
}

// helpers writes the package's one decode, encode and check of a wire type, which
// a package's exported decode and encode functions call, adding what is their
// own (a size limit, say).
func (g *goGen) helpers(pkgName string) {
	g.imports[wireImport] = true
	g.imports["fmt"] = true
	g.imports["reflect"] = true
	g.p("// decode decodes data, one JSON document, as a T, one of the package's wire")
	g.p("// types, and checks its rules. A failure is an *wire.InvalidError that names the")
	g.p("// field and the rule, never the value.")
	g.p("func decode[T any](data []byte) (T, error) {")
	g.p("var value T")
	g.p("if err := json.Unmarshal(data, &value, wireOptions); err != nil {")
	g.p("return value, wire.Refusal(err)")
	g.p("}")
	g.p("if err := check(value); err != nil {")
	g.p("return value, err")
	g.p("}")
	g.p("return value, nil")
	g.p("}")
	g.p("")
	g.p("// encode returns the JSON of value, one of the package's wire types, after")
	g.p("// checking it as decode would.")
	g.p("func encode[T any](value T) ([]byte, error) {")
	g.p("if err := check(value); err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("data, err := json.Marshal(value, wireOptions)")
	g.p("if err != nil {")
	g.p("return nil, wire.Refusal(err)")
	g.p("}")
	g.p("return data, nil")
	g.p("}")
	g.p("")
	g.p("// check runs the rule check of a wire type. A value that is absent (a nil")
	g.p("// interface, or a nil pointer) is refused as required.")
	g.p("func check(value any) error {")
	g.p("if value == nil {")
	g.p("return wire.Required(\"\")")
	g.p("}")
	g.p("// A nil pointer to a wire type has methods, and calling them would panic.")
	g.p("if pointer := reflect.ValueOf(value); pointer.Kind() == reflect.Pointer && pointer.IsNil() {")
	g.p("return wire.Required(\"\")")
	g.p("}")
	g.p("checked, ok := value.(interface{ validate() error })")
	g.p("if !ok {")
	g.p("return fmt.Errorf(\"%s: %%T is not a type of the wire\", value)", pkgName)
	g.p("}")
	g.p("return checked.validate()")
	g.p("}")
}

// A goGen writes one generated Go file.
type goGen struct {
	buf     bytes.Buffer
	imports map[string]bool
	// unions are the package's unions, by name, for what inline fields need.
	unions map[string]*Union
	// aliases are the names a file gives the packages it imports under another
	// name than their last path element.
	aliases map[string]string
}

func (g *goGen) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

// finish returns the file's formatted source.
func (g *goGen) finish(pkgName string) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader + "\n\n")
	fmt.Fprintf(&out, "package %s\n\n", pkgName)
	var paths []string
	for path := range g.imports {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	out.WriteString("import (\n")
	// The standard library first, then this module, as goimports groups them.
	for _, module := range []bool{false, true} {
		for _, path := range paths {
			if strings.Contains(strings.SplitN(path, "/", 2)[0], ".") == module {
				if alias, ok := g.aliases[path]; ok {
					fmt.Fprintf(&out, "\t%s %q\n", alias, path)
				} else {
					fmt.Fprintf(&out, "\t%q\n", path)
				}
			}
		}
		if !module {
			out.WriteString("\n")
		}
	}
	out.WriteString(")\n\n")
	out.Write(g.buf.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated code does not format: %w\n%s", err, out.Bytes())
	}
	return formatted, nil
}

// A member is what an object's decoder reads: a field, or the tag of a variant.
type member struct {
	json  string
	field *Field
	// tag is the tag value that a variant's tag member must hold.
	tag string
	// required members are counted in the decoder's bit set.
	required bool
	// inline is the inline field whose union this member belongs to: the tag or
	// the content of the union.
	inline *Field
	// content is whether a member of an inline union is its content.
	content bool
}

func (g *goGen) members(s *Struct) []member {
	var members []member
	// The variant of an adjacently tagged union is decoded from the union's
	// content, where the tag is not.
	if s.Union != nil && s.Union.TagName != "" && s.Union.ContentName == "" {
		members = append(members, member{json: s.Union.TagName, tag: s.Tag, required: true})
	}
	for _, f := range s.Fields {
		if f.Inline {
			union := g.unions[f.Type.Name]
			members = append(members,
				member{json: union.TagName, inline: f, required: true},
				member{json: union.ContentName, inline: f, content: true, required: true})
			continue
		}
		members = append(members, member{json: f.JSON, field: f, required: f.Required})
	}
	return members
}

func (g *goGen) structure(s *Struct) error {
	members := g.members(s)
	if len(members) > 64 {
		return fmt.Errorf("%s: a wire struct has at most 64 members", s.Name)
	}
	g.decoder(s, members)
	if s.Union != nil && s.Union.TagName != "" || len(s.Embeds) > 0 || hasInline(s) || s.Unknown != nil {
		g.encoder(s)
	}
	g.validator(s)
	return nil
}

// decoder writes UnmarshalJSONFrom of a struct.
func (g *goGen) decoder(s *Struct, members []member) {
	g.imports["encoding/json/jsontext"] = true
	if s.Open {
		g.p("// UnmarshalJSONFrom decodes the JSON object of %s: it ignores a member that", s.Name)
		g.p("// the type does not have, and refuses a required member that is missing, a")
		g.p("// null, and a value of another JSON kind than the member's, naming the member.")
	} else {
		g.p("// UnmarshalJSONFrom decodes the JSON object of %s: it refuses a member that", s.Name)
		g.p("// the type does not have, a required member that is missing, a null, and a")
		g.p("// value of another JSON kind than the member's, naming the member.")
	}
	g.p("func (v *%s) UnmarshalJSONFrom(dec *jsontext.Decoder) error {", s.Name)
	g.p("*v = %s{}", s.Name)
	g.p("if err := wire.BeginObject(dec); err != nil {")
	g.p("return err")
	g.p("}")
	required := 0
	for _, m := range members {
		if m.required {
			required++
		}
	}
	if required > 0 {
		g.p("var seen uint64")
	}
	for _, f := range s.Fields {
		if f.Inline {
			g.p("var tag string")
			g.p("var content jsontext.Value")
		}
	}
	g.p("for {")
	g.p("name, more, err := wire.NextMember(dec)")
	g.p("if err != nil {")
	g.p("return err")
	g.p("}")
	g.p("if !more {")
	g.p("break")
	g.p("}")
	g.p("switch name {")
	for i, m := range members {
		g.p("case %s:", strconv.Quote(m.json))
		if m.required {
			g.p("seen |= 1 << %d", i)
		}
		switch {
		case m.inline != nil && m.content:
			g.p("content, err = wire.ReadRaw(dec)")
			g.p("if err != nil {")
			g.p("return wire.In(%s, err)", strconv.Quote(m.json))
			g.p("}")
		case m.inline != nil:
			g.p("tag, err = wire.ReadString(dec)")
			g.p("if err != nil {")
			g.p("return wire.In(%s, err)", strconv.Quote(m.json))
			g.p("}")
		case m.field == nil:
			g.tagMember(m)
		default:
			g.field(m.field)
		}
	}
	g.p("default:")
	if s.Unknown != nil {
		g.p("raw,err := wire.ReadRaw(dec)")
		g.p("if err!=nil{return wire.In(name,err)}")
		g.p("if v.%s==nil {v.%s=make(map[string]jsontext.Value)}", s.Unknown.Name, s.Unknown.Name)
		g.p("v.%s[name]=raw", s.Unknown.Name)
	} else if s.Open {
		g.p("if err := dec.SkipValue(); err != nil {")
		g.p("return err")
		g.p("}")
	} else {
		g.p("return wire.Unknown(name)")
	}
	g.p("}")
	g.p("}")
	for i, m := range members {
		if m.required {
			g.p("if seen&(1<<%d) == 0 {", i)
			g.p("return wire.Required(%s)", strconv.Quote(m.json))
			g.p("}")
		}
	}
	for _, f := range s.Fields {
		if f.Inline {
			g.p("value, err := decode%sParts(tag, content)", f.Type.Name)
			g.p("if err != nil {")
			g.p("return err")
			g.p("}")
			g.p("v.%s = value", f.Name)
		}
	}
	g.p("return nil")
	g.p("}")
	g.p("")
}

// encoder writes MarshalJSONTo of a struct that json cannot encode as it is:
// the variant of a tagged union, which writes the tag the struct does not hold
// before its members, and a struct with embedded structs, whose members it
// writes as its own.
func (g *goGen) encoder(s *Struct) {
	g.imports["encoding/json/jsontext"] = true
	g.imports["encoding/json/v2"] = true
	switch {
	case s.Union != nil && s.Union.ContentName != "":
		g.adjacentEncoder(s)
		return
	case hasInline(s):
		g.inlineEncoder(s)
		return
	}
	if s.Union != nil {
		g.p("// MarshalJSONTo encodes %s as a JSON object that starts with its tag.", s.Name)
	} else {
		g.p("// MarshalJSONTo encodes %s as a JSON object with the members of the structs", s.Name)
		g.p("// it embeds among its own.")
	}
	g.p("func (v %s) MarshalJSONTo(enc *jsontext.Encoder) error {", s.Name)
	if s.Unknown != nil {
		g.p("if err:=wire.CheckUnknown(v.%s,%s);err!=nil{return err}", s.Unknown.Name, quoted(structMemberNames(s)))
	}
	g.p("return json.MarshalEncode(enc, struct {")
	var values []string
	if s.Union != nil && s.Union.TagName != "" {
		g.p("Tag string `json:%s`", strconv.Quote(s.Union.TagName))
		values = append(values, strconv.Quote(s.Tag))
	}
	for _, f := range s.Fields {
		option := ""
		if !f.Required {
			option = ",omitzero"
		}
		g.p("%s %s `json:%s`", f.Name, f.Type.Src, strconv.Quote(f.JSON+option))
		values = append(values, "v."+f.Name)
	}
	if s.Unknown != nil {
		g.p("%s map[string]jsontext.Value `json:\",embed\"`", s.Unknown.Name)
		values = append(values, "v."+s.Unknown.Name)
	}
	g.p("}{%s})", strings.Join(values, ", "))
	g.p("}")
	g.p("")
}

// tagMember writes the read of the tag of a variant, which must be the
// variant's.
func (g *goGen) tagMember(m member) {
	g.p("tag, err := wire.ReadString(dec)")
	g.p("if err != nil {")
	g.p("return wire.In(%s, err)", strconv.Quote(m.json))
	g.p("}")
	g.p("if tag != %s {", strconv.Quote(m.tag))
	g.p("return wire.UnknownTag(%s, %s)", strconv.Quote(m.json), strconv.Quote(m.tag))
	g.p("}")
}

// field writes the read of the member a field is.
func (g *goGen) field(f *Field) {
	wraps := []string{strconv.Quote(f.JSON)}
	target := "v." + f.Name
	if f.Type.Kind == KindPointer {
		if f.TriState {
			g.p("var value %s", f.Type.Elem.Src)
			g.decode(f.Type.Elem, "value", wraps, 0)
			g.p("%s = &value", target)
			return
		}
		if f.Nullable || f.NullAsAbsent {
			// Nullable and null-as-absent fields both read null as nil.
			g.p("if wire.IsNull(dec) {")
			g.p("if _, err := dec.ReadToken(); err != nil {")
			g.p("return %s", wrapError(wraps, "err"))
			g.p("}")
			g.p("} else {")
			g.pointer(f, target, wraps)
			g.p("}")
			return
		}
		g.p("if wire.IsNull(dec) {")
		g.p("return %s", wrapError(wraps, "wire.Null()"))
		g.p("}")
		g.pointer(f, target, wraps)
		return
	}
	g.decode(f.Type, target, wraps, 0)
}

// pointer writes the read of the value that an optional or a nullable member
// points to.
func (g *goGen) pointer(f *Field, target string, wraps []string) {
	g.p("var value %s", f.Type.Elem.Src)
	g.decode(f.Type.Elem, "value", wraps, 0)
	g.p("%s = &value", target)
}

// wrapError returns the expression of err as the refusal of the value that the
// path elements, outermost first, lead to.
func wrapError(elems []string, err string) string {
	for i := len(elems) - 1; i >= 0; i-- {
		err = fmt.Sprintf("wire.In(%s, %s)", elems[i], err)
	}
	return err
}

// decode writes the statements that read one JSON value of type t into target.
func (g *goGen) decode(t *Type, target string, wraps []string, depth int) {
	fail := "return " + wrapError(wraps, "err")
	if t.Qualifier != "" && (t.Kind == KindUnion || t.Kind == KindString) {
		g.p("u,err := %s.Decode%sJSONFrom(dec)", t.Qualifier, t.Name)
		g.check(fail)
		g.p("%s = u", target)
		return
	}
	switch t.Kind {
	case KindPointer:
		g.p("if dec.PeekKind() == 'n' {")
		g.p("if _, err := dec.ReadToken(); err != nil { %s }", fail)
		g.p("%s = nil", target)
		g.p("} else {")
		g.p("var pointed %s", t.Elem.Src)
		g.decode(t.Elem, "pointed", wraps, depth+1)
		g.p("%s = &pointed", target)
		g.p("}")
	case KindString:
		g.p("s, err := wire.ReadString(dec)")
		g.check(fail)
		g.p("%s = %s", target, convert(t, "s"))
	case KindBool:
		g.p("b, err := wire.ReadBool(dec)")
		g.check(fail)
		g.p("%s = %s", target, convert(t, "b"))
	case KindUint:
		g.p("n, err := wire.ReadUint(dec, %s)", bitsOf(t))
		g.check(fail)
		g.p("%s = %s", target, integer(t, "uint64", "n"))
	case KindInt:
		g.p("n, err := wire.ReadInt(dec, %s)", bitsOf(t))
		g.check(fail)
		g.p("%s = %s", target, integer(t, "int64", "n"))
	case KindFloat:
		g.p("f, err := wire.ReadFloat(dec)")
		g.check(fail)
		g.p("%s = %s", target, convert(t, "f"))
	case KindRaw:
		g.p("raw, err := wire.ReadRaw(dec)")
		g.check(fail)
		g.p("%s = raw", target)
	case KindStruct:
		g.p("if err := %s.UnmarshalJSONFrom(dec); err != nil {", target)
		g.p("%s", fail)
		g.p("}")
	case KindUnion:
		g.p("u, err := decode%s(dec)", t.Name)
		g.check(fail)
		g.p("%s = u", target)
	case KindSlice:
		g.slice(t, target, wraps, depth, fail)
	case KindMap:
		g.mapping(t, target, wraps, depth, fail)
	}
}

func (g *goGen) check(fail string) {
	g.p("if err != nil {")
	g.p("%s", fail)
	g.p("}")
}

// convert returns value, of the basic type, as the possibly named type t.
func convert(t *Type, value string) string {
	if t.Name != "" {
		return fmt.Sprintf("%s(%s)", t.Name, value)
	}
	return value
}

// integer returns value, of the type that the reads of integers return (int64
// or uint64), as the field's type t, converted only when they differ.
func integer(t *Type, read, value string) string {
	if t.Src == read {
		return value
	}
	return fmt.Sprintf("%s(%s)", t.Src, value)
}

func bitsOf(t *Type) string {
	if t.Bits == 0 {
		return "wire.IntBits"
	}
	return strconv.Itoa(t.Bits)
}

func (g *goGen) slice(t *Type, target string, wraps []string, depth int, fail string) {
	items, element := fmt.Sprintf("items%d", depth), fmt.Sprintf("element%d", depth)
	g.p("if err := wire.BeginArray(dec); err != nil {")
	g.p("%s", fail)
	g.p("}")
	g.p("%s := %s{}", items, t.Src)
	g.p("for {")
	g.p("more, err := wire.NextElement(dec)")
	g.check(fail)
	g.p("if !more {")
	g.p("break")
	g.p("}")
	g.p("var %s %s", element, t.Elem.Src)
	g.p("{")
	g.decode(t.Elem, element, append(slices.Clone(wraps), fmt.Sprintf("wire.Index(len(%s))", items)), depth+1)
	g.p("}")
	g.p("%s = append(%s, %s)", items, items, element)
	g.p("}")
	g.p("%s = %s", target, items)
}

func (g *goGen) mapping(t *Type, target string, wraps []string, depth int, fail string) {
	entries, element, key := fmt.Sprintf("entries%d", depth), fmt.Sprintf("element%d", depth), fmt.Sprintf("key%d", depth)
	g.p("if err := wire.BeginObject(dec); err != nil {")
	g.p("%s", fail)
	g.p("}")
	g.p("%s := %s{}", entries, t.Src)
	g.p("for {")
	g.p("%s, more, err := wire.NextMember(dec)", key)
	g.check(fail)
	g.p("if !more {")
	g.p("break")
	g.p("}")
	g.p("var %s %s", element, t.Elem.Src)
	g.p("{")
	g.decode(t.Elem, element, append(slices.Clone(wraps), fmt.Sprintf("wire.Key(%s)", key)), depth+1)
	g.p("}")
	g.p("%s[%s] = %s", entries, convert(t.Key, key), element)
	g.p("}")
	g.p("%s = %s", target, entries)
}

// validator writes validate of a struct: every rule of every field, in
// declaration order, then the rules across fields.
func (g *goGen) validator(s *Struct) {
	g.p("// validate checks the rules of the fields of %s, and reports every one that", s.Name)
	g.p("// is broken.")
	var body goGen
	body.imports = g.imports
	for _, f := range s.Fields {
		body.fieldRules(f)
	}
	if s.Unknown != nil {
		body.p("r.Check(\"\",wire.CheckUnknown(v.%s,%s))", s.Unknown.Name, quoted(structMemberNames(s)))
	}
	for _, embedded := range s.EmbedChecks {
		body.p("r.Check(\"\",v.%s.check())", embedded)
	}
	if s.Check {
		body.p("r.Check(\"\", v.check())")
	}
	if body.buf.Len() == 0 {
		g.p("func (%s) validate() error {", s.Name)
		g.p("return nil")
		g.p("}")
		g.p("")
		return
	}
	g.p("func (v %s) validate() error {", s.Name)
	g.p("var r wire.Report")
	g.buf.Write(body.buf.Bytes())
	g.p("return r.Err()")
	g.p("}")
	g.p("")
}

func (g *goGen) fieldRules(f *Field) {
	path := strconv.Quote(f.JSON)
	expr := "v." + f.Name
	t := f.Type
	if t.Kind == KindPointer {
		var inner goGen
		inner.imports = g.imports
		inner.value(t.Elem, "(*"+expr+")", f.Rules, path, "r", 0)
		if inner.buf.Len() == 0 {
			return
		}
		g.p("if %s != nil {", expr)
		g.buf.Write(inner.buf.Bytes())
		g.p("}")
		return
	}
	g.value(t, expr, f.Rules, path, "r", 0)
}

// value writes the checks of the value expr of type t: its rules, and, for a
// struct or a union, its own checks.
func (g *goGen) value(t *Type, expr string, rules []Rule, path, report string, depth int) {
	if t.Kind == KindPointer {
		g.p("if %s != nil {", expr)
		g.value(t.Elem, "(*"+expr+")", rules, path, report, depth+1)
		g.p("}")
		return
	}

	switch {
	case t.Kind == KindStruct && !t.Opaque:
		g.p("%s.Nest(%s, %s.validate())", report, path, expr)
	case t.Kind == KindUnion && t.Qualifier == "":
		g.p("%s.Nest(%s, validate%s(%s))", report, path, t.Name, expr)
	}
	var each, keys *Rule
	for i, rule := range rules {
		switch rule.Kind {
		case RuleEach:
			each = &rules[i]
		case RuleKeys:
			keys = &rules[i]
		default:
			g.rule(t, expr, rule, path, report, depth)
		}
	}
	if t.Kind != KindSlice && t.Kind != KindMap {
		return
	}
	// The elements of a slice or the entries of a map are visited once, for
	// the rules of the keys, the rules of the elements and their own checks.
	var eachRules, keyRules []Rule
	if each != nil {
		eachRules = each.Inner
	}
	if keys != nil {
		keyRules = keys.Inner
	}
	if each != nil || needsDive(t.Elem) {
		g.each(t, expr, eachRules, keyRules, path, report, depth)
	} else if keys != nil {
		g.keys(t, expr, keyRules, path, report, depth)
	}
}

// needsDive reports whether a value of type t has checks of its own.
func needsDive(t *Type) bool {
	return t.Kind == KindStruct && !t.Opaque || t.Kind == KindUnion
}

func (g *goGen) rule(t *Type, expr string, rule Rule, path, report string, depth int) {
	switch rule.Kind {
	case RuleChars:
		g.p("%s.Chars(%s, %s, %s)", report, path, g.asString(t, expr), bounds(rule))
	case RuleBytes:
		g.p("%s.Bytes(%s, %s, %s)", report, path, g.asString(t, expr), bounds(rule))
	case RuleItems:
		g.p("%s.Items(%s, len(%s), %s)", report, path, expr, bounds(rule))
	case RuleRange:
		switch t.Kind {
		case KindInt:
			g.p("%s.Int(%s, int64(%s), %s)", report, path, expr, bounds(rule))
		case KindFloat:
			g.p("%s.Float(%s, float64(%s), %s)", report, path, expr, floatBounds(rule))
		default:
			g.p("%s.Uint(%s, uint64(%s), %s)", report, path, expr, bounds(rule))
		}
	case RuleEq:
		switch t.Kind {
		case KindString:
			g.p("%s.EqString(%s, %s, %s)", report, path, g.asString(t, expr), strconv.Quote(rule.Value))
		case KindInt:
			g.p("%s.EqInt(%s, int64(%s), int64(%s))", report, path, expr, rule.Value)
		default:
			g.p("%s.EqUint(%s, uint64(%s), uint64(%s))", report, path, expr, rule.Value)
		}
	case RuleOneOf:
		quoted := make([]string, len(rule.Values))
		for i, value := range rule.Values {
			quoted[i] = strconv.Quote(value)
		}
		g.p("%s.OneOf(%s, %s, %s)", report, path, g.asString(t, expr), strings.Join(quoted, ", "))
	case RulePattern:
		g.p("%s.Pattern(%s, %s, %s)", report, path, g.asString(t, expr), rule.Value)
	case RuleNoNUL:
		g.p("%s.NoNUL(%s, %s)", report, path, g.asString(t, expr))
	case RuleUnique:
		g.p("wire.Unique(&%s, %s, %s)", report, path, expr)
	case RuleFunc:
		g.p("%s.Check(%s, %s(%s))", report, path, rule.Value, expr)
	}
}

// keyString returns key, a map's key, as a string.
func keyString(t *Type, key string) string {
	if t.Name != "" {
		return "string(" + key + ")"
	}
	return key
}

func (g *goGen) asString(t *Type, expr string) string {
	if t.Name != "" && t.Kind == KindString {
		return "string(" + expr + ")"
	}
	return expr
}

// bounds writes the wire.Bounds of a rule.
func bounds(rule Rule) string {
	src := func(b *Bound) string {
		if _, err := strconv.ParseInt(b.Src, 10, 64); err == nil {
			return b.Src
		}
		return "int64(" + b.Src + ")"
	}
	switch {
	case rule.Min != nil && rule.Max != nil:
		return fmt.Sprintf("wire.Between(%s, %s)", src(rule.Min), src(rule.Max))
	case rule.Min != nil:
		return fmt.Sprintf("wire.AtLeast(%s)", src(rule.Min))
	default:
		return fmt.Sprintf("wire.AtMost(%s)", src(rule.Max))
	}
}

// floatBounds writes the wire.FloatBounds of the range rule of a float.
func floatBounds(rule Rule) string {
	src := func(b *Bound) string {
		return strconv.FormatFloat(b.Float, 'g', -1, 64)
	}
	switch {
	case rule.Min != nil && rule.Max != nil:
		return fmt.Sprintf("wire.FloatBetween(%s, %s)", src(rule.Min), src(rule.Max))
	case rule.Min != nil:
		return fmt.Sprintf("wire.FloatAtLeast(%s)", src(rule.Min))
	default:
		return fmt.Sprintf("wire.FloatAtMost(%s)", src(rule.Max))
	}
}

// each writes the checks of every element of a slice or every entry of a map:
// the rules of the keys, the inner rules of the elements, and the elements' own
// checks.
func (g *goGen) each(t *Type, expr string, inner, keyRules []Rule, path, report string, depth int) {
	outer := fmt.Sprintf("group%d", depth)
	item := fmt.Sprintf("item%d", depth)
	g.p("{")
	g.p("var %s wire.Report", outer)
	if t.Kind == KindSlice {
		g.p("for i, e := range %s {", expr)
		g.elementChecks(t.Elem, "e", inner, "wire.Index(i)", outer, item, depth)
	} else {
		g.imports["maps"] = true
		g.imports["slices"] = true
		g.p("for _, k := range slices.Sorted(maps.Keys(%s)) {", expr)
		if keyRules != nil {
			key := fmt.Sprintf("key%d", depth)
			g.p("var %s wire.Report", key)
			g.value(t.Key, "k", keyRules, `""`, key, depth+1)
			g.p("%s.Nest(wire.Key(%s), %s.Err())", outer, keyString(t.Key, "k"), key)
		}
		g.p("e := %s[k]", expr)
		g.elementChecks(t.Elem, "e", inner, "wire.Key("+keyString(t.Key, "k")+")", outer, item, depth)
	}
	g.p("}")
	g.p("%s.Nest(%s, %s.Err())", report, path, outer)
	g.p("}")
}

func (g *goGen) elementChecks(t *Type, expr string, rules []Rule, elem, outer, item string, depth int) {
	if len(rules) == 0 {
		g.value(t, expr, nil, elem, outer, depth+1)
		return
	}
	g.p("var %s wire.Report", item)
	g.value(t, expr, rules, `""`, item, depth+1)
	g.p("%s.Nest(%s, %s.Err())", outer, elem, item)
}

// keys writes the checks of the keys of a map.
func (g *goGen) keys(t *Type, expr string, inner []Rule, path, report string, depth int) {
	outer := fmt.Sprintf("keys%d", depth)
	item := fmt.Sprintf("key%d", depth)
	g.imports["maps"] = true
	g.imports["slices"] = true
	g.p("{")
	g.p("var %s wire.Report", outer)
	g.p("for _, k := range slices.Sorted(maps.Keys(%s)) {", expr)
	g.p("var %s wire.Report", item)
	g.value(t.Key, "k", inner, `""`, item, depth+1)
	g.p("%s.Nest(wire.Key(%s), %s.Err())", outer, keyString(t.Key, "k"), item)
	g.p("}")
	g.p("%s.Nest(%s, %s.Err())", report, path, outer)
	g.p("}")
}

// union writes the decoder and the checks of a union.
func (g *goGen) union(u *Union) {
	g.imports["encoding/json/jsontext"] = true
	g.imports["fmt"] = true
	var objects, scalars []*Struct
	for _, v := range u.Variants {
		if v.Scalar != nil {
			scalars = append(scalars, v)
		} else {
			objects = append(objects, v)
		}
	}
	if u.ContentName != "" {
		g.adjacentDecoder(u)
		g.adjacentValidator(u)
		return
	}
	kind := "object"
	if len(scalars) > 0 {
		kind = "value"
	}
	g.p("// decode%s decodes the JSON %s of a %s, whichever variant it is.", u.Name, kind, u.Name)
	g.p("func decode%s(dec *jsontext.Decoder) (%s, error) {", u.Name, u.Name)
	if len(scalars) == 0 {
		g.objectVariants(u, objects)
	} else {
		g.p("switch dec.PeekKind() {")
		for _, v := range scalars {
			g.scalarVariant(v)
		}
		if len(objects) > 0 {
			g.p("case '{':")
			g.objectVariants(u, objects)
		}
		g.p("}")
		g.p("return nil, wire.NoVariant(%s)", quoted(variantNames(u)))
	}
	g.p("}")
	g.p("")

	g.p("// validate%s checks the rules of the variant that v is.", u.Name)
	g.p("func validate%s(v %s) error {", u.Name, u.Name)
	g.p("switch v := v.(type) {")
	g.p("case nil:")
	g.p("return wire.Required(\"\")")
	for _, v := range u.Variants {
		g.p("case %s:", v.Name)
		g.validateVariant(v)
		g.p("case *%s:", v.Name)
		g.p("if v == nil {")
		g.p("return fmt.Errorf(\"a nil %%T is not a variant of %s\", v)", u.Name)
		g.p("}")
		g.validateVariant(v)
	}
	g.p("}")
	g.p("return fmt.Errorf(\"%%T is not a variant of %s\", v)", u.Name)
	g.p("}")
	g.p("")
}

func variantNames(u *Union) []string {
	names := make([]string, len(u.Variants))
	for i, v := range u.Variants {
		names[i] = v.Name
	}
	return names
}

// quoted returns names as the arguments of a call.
func quoted(names []string) string {
	items := make([]string, len(names))
	for i, name := range names {
		items[i] = strconv.Quote(name)
	}
	return strings.Join(items, ", ")
}

// validateVariant writes the return of the check of a variant: a scalar has no
// rule but its JSON kind.
func (g *goGen) validateVariant(v *Struct) {
	if v.Scalar != nil {
		g.p("return nil")
		return
	}
	g.p("return v.validate()")
}

// scalarVariant writes the case of a union's decoder that reads the variant
// that is a JSON string, number or boolean.
func (g *goGen) scalarVariant(v *Struct) {
	t := v.Scalar
	switch t.Kind {
	case KindString:
		g.p("case '\"':")
		g.p("s, err := wire.ReadString(dec)")
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("return %s(s), nil", v.Name)
	case KindBool:
		g.p("case 't', 'f':")
		g.p("b, err := wire.ReadBool(dec)")
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("return %s(b), nil", v.Name)
	case KindFloat:
		g.p("case '0':")
		g.p("f, err := wire.ReadFloat(dec)")
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("return %s(f), nil", v.Name)
	case KindUint:
		g.p("case '0':")
		g.p("n, err := wire.ReadUint(dec, %s)", bitsOf(t))
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("return %s(n), nil", v.Name)
	case KindInt:
		g.p("case '0':")
		g.p("n, err := wire.ReadInt(dec, %s)", bitsOf(t))
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("return %s(n), nil", v.Name)
	}
}

// objectVariants writes the statements of a union's decoder that read the
// variants that are objects: they all return.
func (g *goGen) objectVariants(u *Union, variants []*Struct) {
	g.p("raw, err := wire.ReadObject(dec)")
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	if u.TagName != "" {
		g.p("tag, err := wire.Tag(raw, %s)", strconv.Quote(u.TagName))
		g.p("if err != nil {")
		g.p("return nil, err")
		g.p("}")
		g.p("switch tag {")
		var tags []string
		for _, v := range variants {
			tags = append(tags, strconv.Quote(v.Tag))
			g.p("case %s:", strconv.Quote(v.Tag))
			g.p("var v %s", v.Name)
			g.p("if err := v.UnmarshalJSONFrom(wire.NewDecoder(raw)); err != nil {")
			g.p("return nil, err")
			g.p("}")
			g.p("return v, nil")
		}
		g.p("}")
		g.p("return nil, wire.UnknownTag(%s, %s)", strconv.Quote(u.TagName), strings.Join(tags, ", "))
		return
	}
	g.p("var found %s", u.Name)
	g.p("matches := 0")
	for _, v := range variants {
		g.p("{")
		g.p("var v %s", v.Name)
		g.p("if v.UnmarshalJSONFrom(wire.NewDecoder(raw)) == nil {")
		g.p("found = v")
		g.p("matches++")
		g.p("}")
		g.p("}")
	}
	g.p("switch matches {")
	g.p("case 1:")
	g.p("return found, nil")
	g.p("case 0:")
	g.p("return nil, wire.NoVariant(%s)", quoted(variantNames(u)))
	g.p("}")
	g.p("return nil, wire.SeveralVariants(%s)", quoted(variantNames(u)))
}

// omitOption is the json option of a field that may be absent.
func omitOption(f *Field) string {
	if f.Required {
		return ""
	}
	return ",omitzero"
}

// adjacentEncoder writes MarshalJSONTo of a variant of an adjacently tagged
// union: the tag and, beside it, the variant's members as the content.
func (g *goGen) adjacentEncoder(s *Struct) {
	g.p("// MarshalJSONTo encodes %s as a JSON object with its tag and, beside it, its", s.Name)
	g.p("// members as the content.")
	g.p("func (v %s) MarshalJSONTo(enc *jsontext.Encoder) error {", s.Name)
	if s.Unknown != nil {
		g.p("if err:=wire.CheckUnknown(v.%s,%s);err!=nil{return err}", s.Unknown.Name, quoted(structMemberNames(s)))
	}
	g.p("type content struct {")
	values := make([]string, len(s.Fields))
	for i, f := range s.Fields {
		g.p("%s %s `json:%s`", f.Name, f.Type.Src, strconv.Quote(f.JSON+omitOption(f)))
		values[i] = "v." + f.Name
	}
	if s.Unknown != nil {
		g.p("%s map[string]jsontext.Value `json:%s`", s.Unknown.Name, strconv.Quote(",embed"))
		values = append(values, "v."+s.Unknown.Name)
	}
	g.p("}")
	g.p("return json.MarshalEncode(enc, struct {")
	g.p("Tag string `json:%s`", strconv.Quote(s.Union.TagName))
	g.p("Content content `json:%s`", strconv.Quote(s.Union.ContentName))
	g.p("}{%s, content{%s}})", strconv.Quote(s.Tag), strings.Join(values, ", "))
	g.p("}")
	g.p("")
}

// inlineEncoder writes MarshalJSONTo of a struct with an inline union: its
// members in their order, and the union's, which its variant encodes as an object
// of its own, in the place of the inline field.
func (g *goGen) inlineEncoder(s *Struct) {
	g.imports["encoding/json/jsontext"] = true
	g.p("// MarshalJSONTo encodes %s as a JSON object whose members include those of", s.Name)
	g.p("// its inline union.")
	g.p("func (v %s) MarshalJSONTo(enc *jsontext.Encoder) error {", s.Name)
	g.p("if err := enc.WriteToken(jsontext.BeginObject); err != nil {")
	g.p("return err")
	g.p("}")
	for _, f := range s.Fields {
		if f.Inline {
			g.p("if err := wire.WriteMembers(enc, v.%s, wireOptions); err != nil {", f.Name)
			g.p("return err")
			g.p("}")
			continue
		}
		if !f.Required {
			if f.Type.Kind == KindBool {
				g.p("if v.%s {", f.Name)
			} else {
				g.p("if v.%s != nil {", f.Name)
			}
		}
		g.p("if err := enc.WriteToken(jsontext.String(%s)); err != nil {", strconv.Quote(f.JSON))
		g.p("return err")
		g.p("}")
		g.p("if err := json.MarshalEncode(enc, v.%s); err != nil {", f.Name)
		g.p("return err")
		g.p("}")
		if !f.Required {
			g.p("}")
		}
	}
	g.p("return enc.WriteToken(jsontext.EndObject)")
	g.p("}")
	g.p("")
}

// adjacentDecoder writes the decoders of an adjacently tagged union: of its
// object, and of its parts, which a struct with the union inline reads from its
// own members.
func (g *goGen) adjacentDecoder(u *Union) {
	tag, content := strconv.Quote(u.TagName), strconv.Quote(u.ContentName)
	g.p("// decode%s decodes the JSON object of a %s, whichever variant it is.", u.Name, u.Name)
	g.p("func decode%s(dec *jsontext.Decoder) (%s, error) {", u.Name, u.Name)
	g.p("tag, content, err := wire.ReadAdjacent(dec, %s, %s)", tag, content)
	g.p("if err != nil {")
	g.p("return nil, err")
	g.p("}")
	g.p("return decode%sParts(tag, content)", u.Name)
	g.p("}")
	g.p("")
	g.p("// decode%sParts decodes the variant of a %s that tag names from its", u.Name, u.Name)
	g.p("// content.")
	g.p("func decode%sParts(tag string, content jsontext.Value) (%s, error) {", u.Name, u.Name)
	g.p("switch tag {")
	var tags []string
	for _, v := range u.Variants {
		tags = append(tags, strconv.Quote(v.Tag))
		g.p("case %s:", strconv.Quote(v.Tag))
		g.p("var v %s", v.Name)
		g.p("if err := v.UnmarshalJSONFrom(wire.NewDecoder(content)); err != nil {")
		g.p("return nil, wire.In(%s, err)", content)
		g.p("}")
		g.p("return v, nil")
	}
	g.p("}")
	g.p("return nil, wire.UnknownTag(%s, %s)", tag, strings.Join(tags, ", "))
	g.p("}")
	g.p("")
}

// adjacentValidator writes the checks of an adjacently tagged union: those of its
// variant, whose paths lie in the content.
func (g *goGen) adjacentValidator(u *Union) {
	content := strconv.Quote(u.ContentName)
	g.p("// validate%s checks the rules of the variant that v is.", u.Name)
	g.p("func validate%s(v %s) error {", u.Name, u.Name)
	g.p("switch v := v.(type) {")
	g.p("case nil:")
	g.p("return wire.Required(\"\")")
	for _, v := range u.Variants {
		g.p("case %s:", v.Name)
		g.p("return wire.NestIn(%s, v.validate())", content)
		g.p("case *%s:", v.Name)
		g.p("if v == nil {")
		g.p("return fmt.Errorf(\"a nil %%T is not a variant of %s\", v)", u.Name)
		g.p("}")
		g.p("return wire.NestIn(%s, v.validate())", content)
	}
	g.p("}")
	g.p("return fmt.Errorf(\"%%T is not a variant of %s\", v)", u.Name)
	g.p("}")
	g.p("")
}

// hasInline reports whether a struct has an inline union.
func hasInline(s *Struct) bool {
	return slices.ContainsFunc(s.Fields, func(f *Field) bool { return f.Inline })
}

// structMemberNames lists the names reserved against retained unknown members.
func structMemberNames(s *Struct) []string {
	var names []string
	if s.Union != nil && s.Union.TagName != "" && s.Union.ContentName == "" {
		names = append(names, s.Union.TagName)
	}
	for _, f := range s.Fields {
		names = append(names, f.JSON)
	}
	return names
}
